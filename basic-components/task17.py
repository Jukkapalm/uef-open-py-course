# Muuttujien nimeäminen
# - Nimi ei voi sisältää jotakin Pythonin varattua sanaa, kuten komentoa, esimerkiksi
# muuttujan nimi ei voi olla if = 10

# - Nimi ei voi sisältää välilyöntejä, esim. "talon pinta ala = 5.4"

# - Ensimmäinen merkki pitää olla kirjain, esim. "5pituus = 3" ei käy

# - Vain kirjaimet, alaviivat ja numerot sallittu, esim "Hei*hoi" ei käy

# Hyviin ohjelmointikäytäntöihin kuuluu, että muuttujille annetaan kuvaavat nimet
# Se helpottaa ohjelmointityötä huomattavasti

# Esimerkiksi

nimi = "Matti"
pituus = 4.5
leveys = 34.2
pinta_ala = 46.5
